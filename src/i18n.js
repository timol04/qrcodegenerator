let lang = 'de';
try {
  const saved = localStorage.getItem('qr-lang');
  if (saved && dict[saved]) lang = saved;
} catch { /* Speicher nicht verfügbar */ }

export const getLang = () => lang;

export function t(key, vars = {}) {
  const s = dict[lang][key] ?? dict.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

/** Wendet die aktuelle Sprache auf alle markierten Elemente und den Dokumenttitel an. */
export function applyI18n() {
  document.documentElement.lang = HTML_LANG[lang];
  document.title = t('doc.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('doc.desc'));
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
}

const listeners = [];
export const onLangChange = (fn) => listeners.push(fn);

export function setLang(next) {
  if (!dict[next] || next === lang) return;
  lang = next;
  try { localStorage.setItem('qr-lang', lang); } catch { /* Speicher nicht verfügbar */ }
  applyI18n();
  listeners.forEach((fn) => fn(lang));
}
